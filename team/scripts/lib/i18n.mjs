// Language of a ShipItRight project and its fixed labels (team/conventions/language.md).
// Labels come from team/i18n/<lang>/<namespace>.json (plugin) and .team/labels.json (project).
// Resolution of a key: project, exact language (pt-BR), base language (pt), then en.
import { readFileSync, existsSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const I18N_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'i18n');
export const NAMESPACES = ['common', 'init', 'dashboard', 'detailed', 'adr', 'questions', 'doc', 'plan', 'gherkin'];
export const CLIENT_NAMESPACES = ['common', 'doc', 'plan', 'gherkin'];

const readJson = (file) => {
  if (!existsSync(file)) return null;
  try { return JSON.parse(readFileSync(file, 'utf8')); } catch (e) { throw new Error(`${file}: invalid JSON (${e.message})`); }
};

// Project language: .team/project.json { "language": "<BCP 47>" }; en when the file or the key is missing.
export function projectLang(dir = '.') {
  const conf = readJson(join(dir, '.team', 'project.json'));
  return (conf && typeof conf.language === 'string' && conf.language.trim()) || 'en';
}

// Short date pattern per language, from the label common.date.short (dd.mm.yyyy, dd/mm/yyyy, yyyy-mm-dd…),
// recorded by loadLabels; without it, Intl decides.
const datePatterns = new Map();

// Flat map { "<namespace>.<key>": label } for the given namespaces, already resolved.
// common is always loaded: it holds common.date.short, used by formatDate.
export function loadLabels(dir = '.', namespaces = NAMESPACES, lang = projectLang(dir)) {
  if (!namespaces.includes('common')) namespaces = ['common', ...namespaces];
  const chain = ['en'];
  const base = lang.split('-')[0];
  if (base !== 'en') chain.push(base);
  if (lang !== base) chain.push(lang);
  const project = readJson(join(dir, '.team', 'labels.json')) || {};
  const out = {};
  for (const ns of namespaces) {
    for (const l of chain) Object.assign(out, prefix(ns, readJson(join(I18N_DIR, l, `${ns}.json`))));
    Object.assign(out, prefix(ns, project[ns]));
  }
  if (typeof out['common.date.short'] === 'string') datePatterns.set(lang, out['common.date.short']);
  return out;
}
const prefix = (ns, dict) => Object.fromEntries(Object.entries(dict || {}).map(([k, v]) => [`${ns}.${k}`, v]));

// t(key, params): {name} interpolation; a plural label is an object of CLDR forms chosen on params.n.
// A missing key is returned as is and recorded in t.missing.
export function makeT(lang, labels) {
  const plural = new Intl.PluralRules(lang);
  const missing = new Set();
  const t = (key, params = {}) => {
    let v = labels[key];
    if (v == null) { missing.add(key); return key; }
    if (typeof v === 'object') v = v[plural.select(Number(params.n ?? 0))] ?? v.other ?? Object.values(v)[0];
    return String(v).replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
  };
  t.missing = missing;
  t.lang = lang;
  return t;
}

// Date of an ISO day (YYYY-MM-DD) in the project language. style: short (common.date.short if loaded, else
// Intl: 02.10.2026 in de), medium, long.
export function formatDate(iso, lang, style = 'short') {
  if (!iso) return '';
  const m = String(iso).match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (!m) return String(iso);
  const pattern = style === 'short' && datePatterns.get(lang);
  if (pattern) return pattern.replace('dd', m[3]).replace('mm', m[2]).replace('yyyy', m[1]);
  const d = new Date(Date.UTC(+m[1], +m[2] - 1, +m[3]));
  const opts = style === 'short' ? { day: '2-digit', month: '2-digit', year: 'numeric' }
    : style === 'medium' ? { day: 'numeric', month: 'short', year: 'numeric' } : { day: 'numeric', month: 'long', year: 'numeric' };
  return new Intl.DateTimeFormat(lang, { ...opts, timeZone: 'UTC' }).format(d);
}

// Writes docs/_assets/i18n.js for doc.js and plan.js: window.SIR_I18N = { lang, labels }.
export function writeClientI18n(dir = '.') {
  const lang = projectLang(dir);
  const labels = loadLabels(dir, CLIENT_NAMESPACES, lang);
  const file = join(dir, 'docs', '_assets', 'i18n.js');
  mkdirSync(dirname(file), { recursive: true });
  const body = `// Generated by team/scripts/i18n-assets.mjs from team/i18n and .team/labels.json: do not edit.\n`
    + `window.SIR_I18N = ${JSON.stringify({ lang, labels }, null, 1)};\n`;
  const before = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (before !== body) writeFileSync(file, body);
  return { file, changed: before !== body };
}
